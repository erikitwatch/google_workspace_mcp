/**
 * Cloudflare Worker that fronts the Google Workspace MCP server running in a
 * Cloudflare Container, published at https://mcp.wmtech.app/wit/google.
 *
 * What it does:
 *   1. Strips the connector prefix (/wit/google) so the FastMCP server sees the
 *      root-relative paths it serves: /mcp, /authorize, /token, /register,
 *      /consent, /oauth2callback, /health.
 *   2. Passes RFC 8414 / RFC 9728 well-known discovery requests through with
 *      the prefix intact, because FastMCP serves them path-aware
 *      (e.g. /.well-known/oauth-authorization-server/wit/google) when the
 *      issuer URL carries a path. It also normalises the "prefix-first" form
 *      some clients try (/wit/google/.well-known/...) onto the path-aware form.
 *   3. Hands every request to a single long-lived container instance and
 *      injects the server's configuration as environment variables, mixing
 *      the non-secret [vars] from wrangler.toml with the Worker secrets.
 */

