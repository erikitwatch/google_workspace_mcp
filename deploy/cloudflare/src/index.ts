// `Env` is generated by `wrangler types` (worker-configuration.d.ts) from the
// [vars] and bindings in wrangler.toml; secrets are typed there too.

function containerEnv(env: Env): Record<string, string> {
  const bag = env as unknown as Record<string, unknown>;
  const out: Record<string, string> = {};
  for (const name of PASSTHROUGH_ENV) {
    const v = bag[name];
    if (typeof v === "string" && v.length > 0) out[name] = v;
  }
  return out;
}

export class WorkspaceMcp extends Container<Env> {
  defaultPort = 8000;
  // Python startup is a few seconds; keep the instance warm across the workday.
  sleepAfter = "4h";
  enableInternet = true; // needs Google APIs and Valkey

  constructor(ctx: DurableObjectState<{}>, env: Env) {
    super(ctx, env);
    this.envVars = containerEnv(env);
  }
}

const WELL_KNOWN = [
  "/.well-known/oauth-authorization-server",
  "/.well-known/oauth-protected-resource",
  "/.well-known/openid-configuration",
];

/**
 * Map the public path to the path the container expects, or null if the
 * request isn't ours (route patterns should prevent that, but be explicit).
 */
function rewritePath(pathname: string, prefix: string): string | null {
  // Path-aware discovery: /.well-known/<doc>/wit/google[...]  -> unchanged
  for (const wk of WELL_KNOWN) {
    if (pathname === wk + prefix || pathname.startsWith(wk + prefix + "/")) {
      return pathname;
    }
  }

  if (pathname !== prefix && !pathname.startsWith(prefix + "/")) return null;

  const rest = pathname.slice(prefix.length) || "/";

  // Prefix-first discovery: /wit/google/.well-known/<doc> -> path-aware form
  for (const wk of WELL_KNOWN) {
    if (rest === wk) {
      // Protected-resource metadata is published for the MCP resource itself.
      return wk === "/.well-known/oauth-protected-resource"
        ? `${wk}${prefix}/mcp`
        : `${wk}${prefix}`;
    }
  }

  return rest;
}

// ---------------------------------------------------------------------------
// IP gate — same rule as the other mcp.wmtech.app connectors. The machine-
// facing paths (MCP endpoint, token/registration endpoints, discovery
// documents) answer only claude.ai's egress range. Browser-facing paths
// (/authorize, /consent, /oauth2callback) stay open to users, and are where
// Cloudflare Access + Duo sit (see deploy/README.md).
// ---------------------------------------------------------------------------

const DEFAULT_ALLOWED_CIDRS = "160.79.104.0/21";

function ipv4ToInt(ip: string): number | null {
  const parts = ip.split(".");
  if (parts.length !== 4) return null;
  let n = 0;
  for (const p of parts) {
    const b = Number(p);
    if (!Number.isInteger(b) || b < 0 || b > 255) return null;
    n = (n << 8) | b;
  }
  return n >>> 0;
}

function ipAllowed(ip: string | null, cidrs: string): boolean {
  if (!ip) return false;
  const addr = ipv4ToInt(ip);
  if (addr === null) return false; // IPv6 not expected from claude.ai; deny
  for (const raw of cidrs.split(",")) {
    const cidr = raw.trim();
    if (!cidr) continue;
    const [base, bitsStr] = cidr.split("/");
    const baseInt = ipv4ToInt(base);
    const bits = bitsStr === undefined ? 32 : Number(bitsStr);
    if (baseInt === null || !Number.isInteger(bits) || bits < 0 || bits > 32) continue;
    const mask = bits === 0 ? 0 : (~0 << (32 - bits)) >>> 0;
    if (((addr & mask) >>> 0) === ((baseInt & mask) >>> 0)) return true;
  }
  return false;
}

/** Container-relative paths that only claude.ai may reach. */
function isMachinePath(target: string): boolean {
  if (target.startsWith("/.well-known/")) return true;
  if (target === "/mcp" || target.startsWith("/mcp/")) return true;
  if (target === "/token" || target === "/register") return true;
  if (target === "/health/ready") return true;
  return false;
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    const prefix = (env.CONNECTOR_PREFIX || "/wit/google").replace(/\/+$/, "");

    const target = rewritePath(url.pathname, prefix);
    if (target === null) {
      return new Response("Not found", { status: 404 });
    }

    if (isMachinePath(target)) {
      const bag = env as unknown as Record<string, unknown>;
      const cidrs =
        typeof bag.ALLOWED_CIDRS === "string" && bag.ALLOWED_CIDRS
          ? bag.ALLOWED_CIDRS
          : DEFAULT_ALLOWED_CIDRS;
      if (!ipAllowed(request.headers.get("CF-Connecting-IP"), cidrs)) {
        return new Response(
          "This endpoint only accepts connections from claude.ai.",
          { status: 403, headers: { "content-type": "text/plain" } },
        );
      }
    }

    url.pathname = target;

    const headers = new Headers(request.headers);
    headers.set("X-Forwarded-Proto", "https");
    headers.set("X-Forwarded-Host", url.host);
    headers.set("X-Forwarded-Prefix", prefix);
    const clientIp = request.headers.get("CF-Connecting-IP");
    if (clientIp) headers.set("X-Real-IP", clientIp);

    const forwarded = new Request(url.toString(), {
      method: request.method,
      headers,
      body: request.body,
      redirect: "manual",
    });

    // One shared instance: MCP sessions are held in-process, and the OAuth
    // proxy state lives in Valkey so a restart doesn't log everyone out.
    const container = getContainer(env.WORKSPACE_MCP, "primary");
    return container.fetch(forwarded);
  },
} satisfies ExportedHandler<Env>;
